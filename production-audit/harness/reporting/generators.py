def write_build_report(path: Path | None = None) -> Path:
    verification = read_json(config.verification_path(), {}) or {}
    suites = verification.get("suites", {})
    lines = [
        "# Build and Test Verification",
        "",
        f"Generated: {utc_now()}",
        "",
        "## Reactor build",
        "",
    ]
    build = suites.get("build", {})
    baseline = suites.get("baseline", {})
    lines.extend(
        [
            f"- Baseline command: `{baseline.get('command','')}`",
            f"- Baseline result: {baseline.get('status','n/a')}, exit {baseline.get('exit_code','n/a')}, {baseline.get('tests_run','n/a')} tests, {baseline.get('failures','n/a')} failures",
            f"- Baseline log: `{baseline.get('log','')}`",
            "",
            f"- Current command: `{build.get('command','')}`",
            f"- Current result: {build.get('status','n/a')}, exit {build.get('exit_code','n/a')}, {build.get('tests_run','n/a')} tests, {build.get('failures','n/a')} failures",
            f"- Current log: `{build.get('log','')}`",
            "",
            "## Test suites",
            "",
            "| Suite | Status | Exit | Tests | Failures | Errors | Skipped |",
            "| --- | --- | --- | --- | --- | --- | --- |",
        ]
    )
    for name in sorted(suites):
        entry = suites[name]
        lines.append(
            f"| {name} | {entry.get('status','n/a')} | {entry.get('exit_code','n/a')} | {entry.get('tests_run','n/a')} | {entry.get('failures','n/a')} | {entry.get('errors','n/a')} | {entry.get('skipped','n/a')} |"
        )
    lines.append("")
    return _write(path or config.reports_root() / "build-and-tests.md", "\n".join(lines))


def write_git_delivery_report(path: Path | None = None) -> Path:
    document = delivery_report()
    lines = [
        "# Git Delivery",
        "",
        f"Generated: {utc_now()}",
        "",
        f"- Delivery records: {document['total']}",
        f"- State summary: {document['state_summary']}",
        "",
        "Git push success is reported separately from technical readiness. A blocked push is",
        "a remote permission or policy outcome, not a software correctness result.",
        "",
        "| Timestamp | Action | State | Commit | Branch | Detail |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for entry in document["deliveries"]:
        detail = str(entry.get("detail", "")).replace("|", "/").replace("\n", " ")[:120]
        lines.append(
            f"| {entry.get('timestamp','')} | {entry.get('action','')} | {entry.get('state','')} | {str(entry.get('commit_sha',''))[:10]} | {entry.get('branch','')} | {detail} |"
        )
    lines.append("")
    return _write(path or config.reports_root() / "git-delivery.md", "\n".join(lines))


def write_remaining_tasks_report(path: Path | None = None) -> Path:
    tasks = load_tasks()
    summary = task_status_summary(tasks)
    lines = [
        "# Remaining Tasks",
        "",
        f"Generated: {utc_now()}",
        "",
        f"- Registered tasks: {len(tasks)}",
        "",
        "| State | Count |",
        "| --- | --- |",
    ]
    for state, count in sorted(summary.items()):
        lines.append(f"| {state} | {count} |")
    lines.extend(["", "## Open tasks by severity", "", "| ID | Severity | Area | Title |", "| --- | --- | --- | --- |"])
    for task in sorted(tasks.values(), key=lambda item: (SEVERITY_ORDER.get(item.severity, 9), item.id)):
        if task.state == "VERIFIED":
            continue
        lines.append(f"| {task.id} | {task.severity} | {task.affected_service} | {task.title.replace('|','/')} |")
    lines.append("")
    return _write(path or config.reports_root() / "remaining-tasks.md", "\n".join(lines))


def write_production_readiness_report(path: Path | None = None) -> Path:
    gates = evaluate_gates()
    predicate = completion_predicate(gates)
    coverage = coverage_summary(load_coverage())
    lines = [
        "# Production Readiness",
        "",
        f"Generated: {utc_now()}",
        "",
        f"**Production ready: {predicate['production_ready']}**",
        "",
        f"- Source coverage: {coverage['reviewed_files']} of {coverage['total_files']} files reviewed ({coverage['percent_reviewed']}%)",
        f"- Failing gates: {', '.join(predicate['failing_gates']) or 'none'}",
        "",
        "| Gate | Name | Status | Detail |",
        "| --- | --- | --- | --- |",
    ]
    for gate in gates:
        detail = (gate.detail or (gate.evidence[0] if gate.evidence else "")).replace("|", "/")
        lines.append(f"| {gate.id} | {gate.name} | {gate.status} | {detail} |")
    lines.extend(
        [
            "",
            "The completion predicate is evaluated from the recorded evidence. No gate value is",
            "hardcoded. A gate that has no executed evidence is reported as pending, blocked or",
            "insufficient evidence, never as a pass.",
            "",
        ]
    )
    return _write(path or config.reports_root() / "production-readiness.md", "\n".join(lines))


def write_e2e_report(path: Path | None = None) -> Path:
    run_id = config.run_identifier()
    e2e_root = config.run_root(run_id) / "e2e-results"
    entries: list[dict[str, Any]] = []
    if e2e_root.exists():
        for candidate in sorted(e2e_root.glob("*.json")):
            entries.append({"file": candidate.name, "document": read_json(candidate, {}) or {}})
    lines = [
        "# End-to-End Verification",
        "",
        f"Generated: {utc_now()}",
        "",
        f"Run identifier: `{run_id}`",
        "",
        "## Artefacts",
        "",
    ]
    for entry in entries:
        document = entry["document"]
        lines.append(f"- `{entry['file']}`: state {document.get('state','n/a')}")
    lines.extend(
        [
            "",
            "## Disclosure",
            "",
            "The end-to-end environment is the repository docker compose stack: PostgreSQL 16,",
            "Redis, Kafka in KRaft mode, Elasticsearch, Keycloak and RustFS are real containers.",
            "The external payment provider is the repository mock provider, so the provider",
            "boundary is simulated while every internal boundary is real.",
            "",
        ]
    )
    return _write(path or config.reports_root() / "e2e.md", "\n".join(lines))


def write_roadmap_report(path: Path | None = None) -> Path:
    tasks = load_tasks()
    lines = [
        "# Refactoring Roadmap",
        "",
        f"Generated: {utc_now()}",
        "",
        "The roadmap is ordered by business risk. Every entry names the design pattern that",
        "resolves it and the evidence that justifies it.",
        "",
        "| Order | ID | Severity | Pattern | Change |",
        "| --- | --- | --- | --- | --- |",
    ]
    ordered = sorted(
        tasks.values(),
        key=lambda item: (SEVERITY_ORDER.get(item.severity, 9), item.priority, item.id),
    )
    for index, task in enumerate(ordered, start=1):
        pattern = task.design_pattern or ""
        change = task.target_implementation or task.title
        lines.append(f"| {index} | {task.id} | {task.severity} | {pattern} | {change.replace('|','/')} |")
    lines.append("")
    return _write(path or config.reports_root() / "refactoring-roadmap.md", "\n".join(lines))


def write_all_reports() -> list[Path]:
    return [
        write_findings_report(),
        write_no_comment_report(),
        write_build_report(),
        write_git_delivery_report(),
        write_remaining_tasks_report(),
        write_production_readiness_report(),
        write_e2e_report(),
        write_roadmap_report(),
    ]
