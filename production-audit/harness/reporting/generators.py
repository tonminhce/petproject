SEVERITY_ORDER = {"CRITICAL": 0, "HIGH": 1, "MEDIUM": 2, "LOW": 3}


def _write(path: Path, content: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return path


def findings_document() -> dict[str, Any]:
    rows: list[dict[str, Any]] = []
    for candidate in sorted(glob.glob(str(config.state_root() / "findings" / "*.json"))):
        document = read_json(Path(candidate), {}) or {}
        for finding in document.get("findings", []):
            rows.append({**finding, "topic": document.get("topic", "")})
    rows.sort(key=lambda row: (SEVERITY_ORDER.get(row.get("severity", ""), 9), row.get("id", "")))
    return {"generated_at": utc_now(), "count": len(rows), "findings": rows}


def write_findings_report(path: Path | None = None) -> Path:
    document = findings_document()
    lines = [
        "# Findings",
        "",
        "Every finding was produced by reading the first-party source, not the documentation.",
        "",
        f"Registry size: {document['count']} findings.",
        "",
        "| ID | Severity | Area | Title |",
        "| --- | --- | --- | --- |",
    ]
    for row in document["findings"]:
        lines.append(
            f"| {row.get('id','')} | {row.get('severity','')} | {row.get('topic','')} | {str(row.get('title','')).replace('|','/')} |"
        )
    lines.extend(
        [
            "",
            "The full evidence for each finding, including file and line references, the root",
            "cause and the proposed fix, is in",
            "`production-audit/runs/run-20261118-a2b6e6fc/source-reviews/` and in the",
            "machine-readable ledger `production-audit/state/findings/`.",
            "",
        ]
    )
    return _write(path or config.reports_root() / "findings.md", "\n".join(lines))


